#!/usr/bin/env node
/**
 * 每次 build 寫入 src/generated/app-bundle-meta.ts，供實機 [APP_BUNDLE_VERSION] 對照 git commit。
 */
import { execSync } from "node:child_process";
import { mkdirSync, writeFileSync } from "node:fs";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const outDir = resolve(root, "src/generated");
const outPath = resolve(outDir, "app-bundle-meta.ts");

function gitValue(args) {
  try {
    return execSync(`git ${args}`, { cwd: root, encoding: "utf8" }).trim();
  } catch {
    return "";
  }
}

const commitHash = gitValue("rev-parse HEAD") || "unknown";
const commitShort = gitValue("rev-parse --short HEAD") || "unknown";
const branch = gitValue("rev-parse --abbrev-ref HEAD") || "unknown";
const buildTime = new Date().toISOString();

mkdirSync(outDir, { recursive: true });

const contents = `/** Auto-generated by scripts/sync-app-bundle-meta.mjs — do not edit. */
export const APP_BUILD_COMMIT = ${JSON.stringify(commitHash)};
export const APP_BUILD_COMMIT_SHORT = ${JSON.stringify(commitShort)};
export const APP_BUILD_BRANCH = ${JSON.stringify(branch)};
export const APP_BUILD_TIME = ${JSON.stringify(buildTime)};
`;

writeFileSync(outPath, contents, "utf8");
console.info("[sync-app-bundle-meta]", {
  commitShort,
  branch,
  buildTime,
  outPath: "src/generated/app-bundle-meta.ts",
});
